export function createProfileDemoConfiguration(
  preset = 'Default',
): DemoConfiguration {
  const selected =
    profilePresets.find((item) => item.id === preset) ?? profilePresets[0];
  return {
    title: 'Profile',
    properties: profileProperties,
    initial: JSON.parse(JSON.stringify(selected.initial)),
    tall: false,
  };
}
