export function createContainerButtonDemoConfiguration(
  preset = 'Default',
): DemoConfiguration {
  const selected =
    containerButtonPresets.find((item) => item.id === preset) ??
    containerButtonPresets[0];
  return {
    title: 'Container button',
    properties: containerButtonProperties,
    initial: JSON.parse(JSON.stringify(selected.initial)),
    tall: false,
  };
}
